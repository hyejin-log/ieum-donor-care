PREFIX = ["", "", "", "선생님 ", "저 ", "혹시 ", "저기요 "]
SUFFIX = ["", "", "", "ㅠㅠ", "..", "!", "?"]


def variants(text: str) -> list[str]:
    """띄어쓰기 없애기, 말끝 바꾸기, 앞뒤 말 붙이기로 변형을 만든다."""
    out = {text.strip()}
    out.add(text.replace(" ", ""))
    out.add(text.replace("요", "요.").strip())
    out.add(text.replace("나요", "나").replace("돼요", "돼").replace("아파요", "아파").replace("어요", "어"))
    return [random.choice(PREFIX) + v.strip() + random.choice(SUFFIX) for v in out]


rows = []
for tid, (label, template, slots) in enumerate(TEMPLATES):
    keys = list(slots)
    for values in itertools.product(*(slots[k] for k in keys)):
        sentence = template.format(**dict(zip(keys, values))).strip()
        for v in variants(sentence):
            rows.append({"text": " ".join(v.split()), "label": label, "template_id": tid})

df = pd.DataFrame(rows).drop_duplicates("text")
# 틀마다 문장 수가 크게 다르면 한 틀이 결과를 좌우하므로, 틀당 최대 24문장으로 맞춘다
df = (df.sample(frac=1, random_state=7)          # 섞은 뒤
        .groupby("template_id").head(24)          # 틀마다 앞에서 24개까지
        .reset_index(drop=True))
out = Path(__file__).with_name("triage_sentences.csv")
df.to_csv(out, index=False, encoding="utf-8-sig")
